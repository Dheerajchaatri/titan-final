import { create } from "zustand";
import { persist } from "zustand/middleware";

export interface Job {
  id: string;
  title: string;
  companyName: string;
  industry: string;
  category: string;
  logo: string;
  location: string;
  salaryRange: string;
  jobType: string;
  experienceRequired: string;
  description: string;
  requirements: string[];
  benefits: string[];
  postedAt: string;
  applicantsCount: number;
  isFeatured: boolean;
  isNew: boolean;
  matchScore?: number;
}

export interface JobApplication {
  id: string;
  jobId: string;
  jobTitle: string;
  companyName: string;
  candidateId: string;
  candidateName: string;
  candidateTitle: string;
  status: "Under Review" | "Shortlisted" | "Interview Scheduled" | "Offer Received" | "Rejected";
  appliedDate: string;
  cvUrl: string;
  coverLetter?: string;
  matchScore: number;
}

export interface FilterSettings {
  keyword: string;
  location: string;
  minSalary: string;
  maxSalary: string;
  experience: string;
  jobType: string;
  isRemote: boolean;
}

interface JobState {
  jobs: Job[];
  applications: JobApplication[];
  savedJobIds: string[];
  filters: FilterSettings;
  setFilters: (filters: Partial<FilterSettings>) => void;
  resetFilters: () => void;
  postJob: (job: Omit<Job, "id" | "postedAt" | "applicantsCount" | "isNew">) => void;
  editJob: (id: string, updatedJob: Partial<Job>) => void;
  deleteJob: (id: string) => void;
  applyJob: (jobId: string, candidateId: string, candidateName: string, candidateTitle: string, coverLetter?: string, matchScore?: number) => void;
  updateApplicationStatus: (applicationId: string, status: JobApplication["status"]) => void;
  toggleSaveJob: (jobId: string) => void;
  calculateMatchScore: (candidateSkills: { name: string; rating: number }[], jobRequirements: string[]) => number;
}

