const initialFilters: FilterSettings = {
  keyword: "",
  location: "",
  minSalary: "Min",
  maxSalary: "Max",
  experience: "Any experience",
  jobType: "All types",
  isRemote: false,
};

export const useJobStore = create<JobState>()(
  persist(
    (set, get) => ({
      jobs: defaultJobs,
      applications: mockApplications,
      savedJobIds: ["job-1", "job-4"],
      filters: initialFilters,

      setFilters: (newFilters) => {
        set((state) => ({
          filters: { ...state.filters, ...newFilters },
        }));
      },

      resetFilters: () => {
        set({ filters: initialFilters });
      },

      postJob: (jobData) => {
        const newJob: Job = {
          ...jobData,
          id: `job-${Math.random().toString(36).substring(7)}`,
          postedAt: "Just now",
          applicantsCount: 0,
          isNew: true,
          matchScore: 100, // Default for testing
        };

        set((state) => ({
          jobs: [newJob, ...state.jobs],
        }));
      },

      editJob: (id, updatedJob) => {
        set((state) => ({
          jobs: state.jobs.map((j) => (j.id === id ? { ...j, ...updatedJob } : j)),
        }));
      },

      deleteJob: (id) => {
        set((state) => ({
          jobs: state.jobs.filter((j) => j.id !== id),
          applications: state.applications.filter((a) => a.jobId !== id),
        }));
      },

      applyJob: (jobId, candidateId, candidateName, candidateTitle, coverLetter, matchScore) => {
        const job = get().jobs.find((j) => j.id === jobId);
        if (!job) return;

        // Check if already applied
        const alreadyApplied = get().applications.some(
          (a) => a.jobId === jobId && a.candidateId === candidateId
        );
        if (alreadyApplied) return;

        const score = matchScore || job.matchScore || 75;

        const newApplication: JobApplication = {
          id: `app-${Math.random().toString(36).substring(7)}`,
          jobId,
          jobTitle: job.title,
          companyName: job.companyName,
          candidateId,
          candidateName,
          candidateTitle,
          status: "Under Review",
          appliedDate: new Date().toLocaleDateString("en-US", {
            month: "short",
            day: "numeric",
            year: "numeric",
          }),
          cvUrl: "/resumes/resume.pdf",
          coverLetter,
          matchScore: score,
        };

        // Increment applicants count
        set((state) => ({
          applications: [newApplication, ...state.applications],
          jobs: state.jobs.map((j) =>
            j.id === jobId ? { ...j, applicantsCount: j.applicantsCount + 1 } : j
          ),
        }));
      },

      updateApplicationStatus: (applicationId, status) => {
        set((state) => ({
          applications: state.applications.map((a) =>
            a.id === applicationId ? { ...a, status } : a
          ),
        }));
      },

      toggleSaveJob: (jobId) => {
        set((state) => {
          const isSaved = state.savedJobIds.includes(jobId);
          return {
            savedJobIds: isSaved
              ? state.savedJobIds.filter((id) => id !== jobId)
              : [...state.savedJobIds, jobId],
          };
        });
      },

      calculateMatchScore: (candidateSkills, jobRequirements) => {
        if (!jobRequirements || jobRequirements.length === 0) return 100;
        
        let matchCount = 0;
        let totalScore = 0;

        jobRequirements.forEach((req) => {
          const matchedSkill = candidateSkills.find(
            (s) => s.name.toLowerCase().includes(req.toLowerCase()) || 
                   req.toLowerCase().includes(s.name.toLowerCase())
          );
          if (matchedSkill) {
            matchCount++;
            totalScore += matchedSkill.rating;
          }
        });

        if (matchCount === 0) return 30; // Base background match
        
        // Calculate weighted percentage
        const matchPercentage = (matchCount / jobRequirements.length) * 100;
        const averageRating = totalScore / matchCount;
        
        // Return average of match scale and specific ratings
        return Math.round((matchPercentage + averageRating) / 2);
      },
    }),
    {
      name: "titan-job-storage-v2",
    }
  )
);
